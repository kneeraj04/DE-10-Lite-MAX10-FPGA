library ieee;
use ieee.std_logic_1164.all;


entity i2c_master_tb is
end i2c_master_tb;


architecture behavior of i2c_master_tb is

    ---------------------------------------------------------------
    -- 500 ps clock
    ---------------------------------------------------------------

    signal clk : std_logic := '0';

    signal reset : std_logic := '1';

    signal start : std_logic := '0';


    ---------------------------------------------------------------
    -- I2C transaction
    ---------------------------------------------------------------

    signal slave_addr : std_logic_vector(6 downto 0)
                        := "1010000";

    signal data_in : std_logic_vector(7 downto 0)
                     := "01010101";


    ---------------------------------------------------------------
    -- I2C bus
    ---------------------------------------------------------------

    signal scl : std_logic;

    signal sda : std_logic;


    ---------------------------------------------------------------
    -- Status
    ---------------------------------------------------------------

    signal busy : std_logic;

    signal done : std_logic;


begin


    ---------------------------------------------------------------
    -- 500 ps clock
    ---------------------------------------------------------------

    clk <= not clk after 250 ps;


    ---------------------------------------------------------------
    -- I2C MASTER
    ---------------------------------------------------------------

    DUT : entity work.i2c_master

        generic map (
            CLK_DIV => 2
        )

        port map (

            clk        => clk,
            reset      => reset,
            start      => start,

            slave_addr => slave_addr,
            data_in    => data_in,

            scl        => scl,
            sda        => sda,

            busy       => busy,
            done       => done

        );


    ---------------------------------------------------------------
    -- SIMPLE I2C SLAVE
    --
    -- Only generates ACK.
    --
    -- Otherwise SDA = Z.
    ---------------------------------------------------------------

    slave_ack : process

    begin

        -----------------------------------------------------------
        -- Release SDA initially
        -----------------------------------------------------------

        sda <= 'Z';


        -----------------------------------------------------------
        -- Wait for START
        -----------------------------------------------------------

        wait until start = '1';


        -----------------------------------------------------------
        -- ADDRESS ACK
        --
        -- Wait for the 8 address clocks.
        -----------------------------------------------------------

        for i in 0 to 7 loop

            wait until rising_edge(scl);

        end loop;


        -----------------------------------------------------------
        -- ACK
        -----------------------------------------------------------

        wait until falling_edge(scl);

        sda <= '0';

        wait until rising_edge(scl);

        wait until falling_edge(scl);

        sda <= 'Z';


        -----------------------------------------------------------
        -- DATA ACK
        --
        -- Wait for 8 data clocks.
        -----------------------------------------------------------

        for i in 0 to 7 loop

            wait until rising_edge(scl);

        end loop;


        -----------------------------------------------------------
        -- ACK
        -----------------------------------------------------------

        wait until falling_edge(scl);

        sda <= '0';

        wait until rising_edge(scl);

        wait until falling_edge(scl);

        sda <= 'Z';


        -----------------------------------------------------------
        -- End
        -----------------------------------------------------------

        wait;

    end process;


    ---------------------------------------------------------------
    -- TEST
    ---------------------------------------------------------------

    stimulus : process

    begin

        -----------------------------------------------------------
        -- RESET
        -----------------------------------------------------------

        reset <= '1';

        wait for 1 ns;

        reset <= '0';

        wait for 1 ns;


        -----------------------------------------------------------
        -- START
        -----------------------------------------------------------

        start <= '1';

        wait for 500 ps;

        start <= '0';


        -----------------------------------------------------------
        -- Wait for completion
        -----------------------------------------------------------

        wait until done = '1';

        wait for 1 ns;


        -----------------------------------------------------------
        -- Finish
        -----------------------------------------------------------

        assert false
            report "I2C transaction completed"
            severity failure;

    end process;


end behavior;